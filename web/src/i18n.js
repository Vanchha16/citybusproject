export const t = (lang) => strings[lang] ?? strings.en;

/** Pick the right language from a {en, km} name object. */
export const label = (obj, lang) => obj?.[lang] ?? obj?.en ?? '';

export function clock(min) {
  const m = ((Math.round(min) % 1440) + 1440) % 1440;
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`;
}

export function distance(meters, lang) {
  const s = t(lang);
  return meters >= 1000 ? s.km((meters / 1000).toFixed(1)) : s.m(Math.max(10, Math.round(meters / 10) * 10));
}

export const roundMin = (x) => Math.max(1, Math.round(x));
